// นิยาม "เงิน" ของร้าน — รวมไว้ที่เดียวทั้งแอป
//
// ก่อนหน้านี้แต่ละหน้าคำนวณเองแยกกัน แล้วค่อยๆ เพี้ยนจนไม่ตรงกัน:
//   - กราฟรายเดือน       นับ total_price + delivery_fee  ✅
//   - ตารางอันดับกล้อง    นับ total_price เฉยๆ            ❌ ค่าส่งหาย
//   - ยอดรวมของลูกค้า     นับ total_price เฉยๆ + นับรายการที่ยกเลิกด้วย ❌
// ผลคือตัวเลขบนหน้าจอเดียวกันบวกกันไม่ลงตัว
//
// กติกาของร้าน (ยืนยันกับเจ้าของแล้ว ก.ย. 2569):
//   รายได้ = ค่าเช่า + ค่าส่ง   (ไม่รวมค่าประกัน เพราะต้องคืนลูกค้า)
//   รายการที่ "ยกเลิก" ไม่นับทุกกรณี
// ══════════════════════════════════════════════════════════════

/** รายการที่เอามานับได้ (ตัดที่ยกเลิกทิ้ง) */
export const isCountable = r => r?.status !== 'cancelled'

/** รายได้เต็มของรายการเช่า = ค่าเช่า + ค่าส่ง */
export const rentalRevenue = r =>
  Number(r?.total_price || 0) + Number(r?.delivery_fee || 0)

/**
 * เงินที่ "รับมาแล้วจริง"
 * คิวที่ยังแค่จอง = ได้มาเฉพาะมัดจำ · ที่เหลือ (กำลังเช่า/คืนแล้ว) = ได้เต็ม
 */
export const cashReceived = r =>
  r?.status === 'booked' ? Number(r?.deposit || 0) : rentalRevenue(r)

/** ยอดที่ยังรอเก็บจากคิวที่จองไว้ */
export const pendingAmount = r =>
  r?.status === 'booked'
    ? Math.max(0, rentalRevenue(r) - Number(r?.deposit || 0))
    : 0
