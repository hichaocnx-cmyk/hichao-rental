// ══════════════════════════════════════════════════════════════
// นิยาม "เงิน" ของร้าน — รวมไว้ที่เดียวทั้งแอป
//
// ก่อนหน้านี้แต่ละหน้าคำนวณเองแยกกัน แล้วค่อยๆ เพี้ยนจนไม่ตรงกัน:
//   - กราฟรายเดือน       นับ total_price + delivery_fee  ✅
//   - ตารางอันดับกล้อง    นับ total_price เฉยๆ            ❌ ค่าส่งหาย
//   - ยอดรวมของลูกค้า     นับ total_price เฉยๆ + นับรายการที่ยกเลิกด้วย ❌
// ผลคือตัวเลขบนหน้าจอเดียวกันบวกกันไม่ลงตัว
//
// กติกาของร้าน (ยืนยันกับเจ้าของแล้ว ก.ย. 2569):
//   รายได้ = ค่าเช่า + ค่าส่ง   (ไม่รวมค่าประกัน เพราะต้องคืนลูกค้า)
//   รายการที่ "ยกเลิก" ไม่นับทุกกรณี
// ══════════════════════════════════════════════════════════════

/** รายการที่เอามานับได้ (ตัดที่ยกเลิกทิ้ง) */
export const isCountable = r => r?.status !== 'cancelled'

/** รายได้เต็มของรายการเช่า = ค่าเช่า + ค่าส่ง */
export const rentalRevenue = r =>
  Number(r?.total_price || 0) + Number(r?.delivery_fee || 0)

/**
 * เงินที่ "รับมาแล้วจริง"
 * คิวที่ยังแค่จอง = ได้มาเฉพาะมัดจำ · ที่เหลือ (กำลังเช่า/คืนแล้ว) = ได้เต็ม
 *
 * ⚠️ มัดจำนับเป็นรายได้ได้ "ไม่เกินค่าเช่า+ค่าส่ง" (แก้ 20 ต.ค. 2569)
 * ร้านเก็บมัดจำ 1,000 แทบทุกคิว แต่หลายคิวค่าเช่าถูกกว่านั้น (เช่น GR3 วันเดียว 400)
 * ส่วนที่เกินคือ "ค่าประกัน" ที่จ่ายล่วงหน้า ต้องคืนลูกค้า ไม่ใช่รายได้
 * เดิมนับมัดจำเต็ม → รายรับ/กำไรของเดือนที่มีคิวจองค้างอยู่สูงเกินจริง
 * แล้วค่อยลดลงเองตอนกดรับกล้อง (เช่น คุณนุ่น พ.ย.: มัดจำ 4,000 ค่าเช่า 2,000 → เคยนับเกิน 2,000)
 * cashReceived + pendingAmount = rentalRevenue เสมอ
 */
export const cashReceived = r =>
  r?.status === 'booked'
    ? Math.min(Number(r?.deposit || 0), rentalRevenue(r))
    : rentalRevenue(r)

/** ยอดที่ยังรอเก็บจากคิวที่จองไว้ */
export const pendingAmount = r =>
  r?.status === 'booked'
    ? Math.max(0, rentalRevenue(r) - Number(r?.deposit || 0))
    : 0

/**
 * วันนี้ตามเวลาเครื่อง (YYYY-MM-DD)
 */
export const todayStr = (d = new Date()) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`

/**
 * นับเข้ายอดได้หรือยัง = ถึงวันรับกล้องแล้ว (start_date ≤ วันนี้)  (เพิ่ม 20 ต.ค. 2569)
 * คิวที่จองไว้วันหลังๆ ของเดือน ยังไม่เอามานับในรายได้/กำไร/จำนวนลูกค้า จนกว่าจะถึงวันนั้น
 * — เจ้าของร้านอยากเห็นยอด "ที่เกิดขึ้นจริงถึงวันนี้" ไม่ใช่ยอดรวมทั้งเดือนล่วงหน้า
 * รายจ่ายใช้กติกาเดียวกัน (วันที่ ≤ วันนี้)
 */
export const hasStarted = (r, today = todayStr()) => (r?.start_date || '') <= today
